# Convertir una temperatura expresada en grados Celsius a su
# equivalente en grados Fahrenheit, sabiendo que F = C × 9 / 5 + 32.

C = float(input("Temperatura en grados Celsius: "))
F = C * 9 / 5 + 32
print(f"La temperatura en grados Fahrenheit es {F}")
